from fastapi import FastAPI
from pydantic import BaseModel
import requests

app = FastAPI()


class APIKeyRequest(BaseModel):
    api_key: str


@app.post("/test-google-api-key")
def test_google_api_key(data: APIKeyRequest):

    url = "https://maps.googleapis.com/maps/api/place/textsearch/json"

    params = {
        "query": "restaurant in Dhaka",
        "key": data.api_key,
    }

    try:
        response = requests.get(url, params=params, timeout=10)
        result = response.json()

        google_status = result.get("status")

        if google_status == "OK":
            return {
                "success": True,
                "message": "Google API key is valid and working.",
                "google_status": google_status,
            }

        return {
            "success": False,
            "message": "Google API key is not working.",
            "google_status": google_status,
            "error": result.get("error_message"),
        }

    except requests.RequestException as e:
        return {
            "success": False,
            "message": "Could not connect to Google API.",
            "error": str(e),
        }